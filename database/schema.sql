create table if not exists public.trash_readings (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  distance_cm double precision not null check (distance_cm between 0 and 57),
  fill_height_cm double precision not null check (fill_height_cm between 0 and 57),
  capacity_percent double precision not null check (capacity_percent between 0 and 100),
  status text not null check (status in ('BELUM PENUH', 'HAMPIR PENUH', 'PENUH')),
  latitude double precision,
  longitude double precision,
  satellites integer,
  gps_valid boolean not null default false
);

create index if not exists trash_readings_created_at_idx
on public.trash_readings (created_at desc);

-- API uses the Supabase service_role key only on the server.
-- Keep this table unavailable to browser anon/authenticated roles.
alter table public.trash_readings enable row level security;
revoke all on table public.trash_readings from anon, authenticated;
